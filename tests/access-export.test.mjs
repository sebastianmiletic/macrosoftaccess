import assert from 'node:assert/strict';
import { accessExportPayload } from '../src/access-export.js';
const text = accessExportPayload([{ name: 'Names', columns: [{ name: 'id', type: 'INTEGER' }, { name: 'name', type: 'TEXT' }, { name: 'price', type: 'REAL' }], rows: [{ id: 1, name: 'Zoë\nSmith', price: 2.5 }, { id: 2, name: '', price: null }] }]);
const lines = text.trimEnd().split('\n');
assert.equal(lines[0], 'MDA-TABLES-2');
assert.equal(lines[1], '1');
assert.equal(lines[10], '0');
assert.equal(lines[11], '2');
assert.equal(lines[12], 'VMQ==');
assert.equal(lines[13], `V${Buffer.from('Zoë\nSmith').toString('base64')}`);
assert.equal(lines.at(-2), 'V');
assert.equal(lines.at(-1), 'N');
const keys = accessExportPayload([{ name: 'Orders', columns: [{ name: 'Store', type: 'TEXT', pk: 2 }, { name: 'Number', type: 'INTEGER', pk: 1 }], rows: [] }]).trimEnd().split('\n');
assert.equal(keys[8], '2');
assert.equal(Buffer.from(keys[9], 'base64').toString(), 'Number');
assert.equal(Buffer.from(keys[10], 'base64').toString(), 'Store');
const date = accessExportPayload([{ name: 'Events', columns: [{ name: 'Started', type: 'DATETIME' }], rows: [{ Started: '2026-10-13 17:08' }] }]);
assert.match(date, /\nDATETIME\n/);
assert.throws(() => accessExportPayload([{ name: 'Photos', columns: [{ name: 'image', type: 'BLOB' }], rows: [] }]), /BLOB/);
assert.throws(() => accessExportPayload([{ name: 'Photos', columns: [{ name: 'image', type: 'TEXT' }], rows: [{ image: new Uint8Array([1]) }] }]), /Binary/);
console.log('PASS: loss-aware Access table export encoding, Unicode, empty values and NULL');
